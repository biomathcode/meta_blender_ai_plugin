"""Floating Sky Shrine — built with the Muse AI Texture addon.

The hero monolith's stone texture is generated by Meta Muse Image via the
addon's own pipeline (api_client -> operators._apply_generated_image ->
nodes PBR material + Muse GN Texture displacement). Everything else is
procedural. Rerunnable: resets the scene first.
"""
import os
import sys
import math

WS = "/Users/coolhead/Documents/work/hackathons/meta_blender_ai_plugin"
SKILL = "/Users/coolhead/.local/share/muse/skills/bundled/muse-core--exact-minimal-literal-tests~v1/skills/blender"
sys.path.insert(0, os.path.join(SKILL, "scripts"))
sys.path.insert(0, WS)

import bpy
import bpy_helpers as H

OUT = os.path.join(WS, "output")
os.makedirs(OUT, exist_ok=True)
BLEND = os.path.join(OUT, "sky_shrine.blend")
FINAL = "--final" in sys.argv

# --- addon ---
import muse_ai_texture
from muse_ai_texture import api_client, operators, utils
muse_ai_texture.register()
print("ADDON_REGISTERED")

H.reset_scene()

# --- materials ---
rock_mat = H.material_preset("Rock", "stone", "#6b6259", scale=6.0, roughness=0.95)
grass_mat = H.material_preset("Grass", "foliage", "#4e7d3a", scale=8.0, roughness=0.9)
stone_mat = H.material_preset("StonePlain", "stone", "#776f63", scale=5.0, roughness=0.9)
wood_mat = H.material_preset("Wood", "wood", "#6e4f30", scale=4.0)
leaf_mat = H.material_preset("Leaves", "foliage", "#3f7031", scale=6.0, roughness=0.9)
cloud_mat = H.material("Cloud", "#f4f7fa", roughness=0.95)
gold_mat = H.material_preset("GoldTrim", "gold", "#c9a227", roughness=0.35)
crystal_mat = H.emission_material("CrystalGlow", "#2ee6c8", 4.0)

# --- floating island: lathe rock + grass cap ---
profile = [(0.0, -2.5), (0.65, -1.85), (1.3, -1.05), (1.85, -0.4), (2.2, -0.05), (2.25, 0.12)]
island = H.add_lathe("IslandRock", profile, segments=48, mat=rock_mat)
H.shade_smooth(island, angle=40)
grass = H.add_cylinder("GrassTop", 2.24, 0.3, vertices=48, location=(0, 0, 0.15), mat=grass_mat)

# --- shrine steps + hero monolith (Muse textured) ---
step1 = H.add_box("Step1", size=(2.1, 2.1, 0.18), location=(0, 0, 0.39), bevel=0.02, mat=stone_mat)
step2 = H.add_box("Step2", size=(1.8, 1.8, 0.18), location=(0, 0, 0.57), bevel=0.02, mat=stone_mat)
monolith = H.add_box("ShrineMonolith", size=(1.35, 1.35, 1.1), location=(0, 0, 1.21), bevel=0.03, mat=stone_mat)
bpy.context.view_layer.objects.active = monolith
mod = H.add_modifier(monolith, "SUBSURF", levels=4, render_levels=4,
                     subdivision_type="SIMPLE")
H.apply_modifiers(monolith)

# pillars + roof + pyramid cap
pillars = []
for sx in (-0.52, 0.52):
    for sy in (-0.52, 0.52):
        p = H.add_cylinder("Pillar", 0.09, 0.78, vertices=20,
                           location=(sx, sy, 2.15), mat=stone_mat)
        pillars.append(p)
roof = H.add_box("RoofSlab", size=(1.62, 1.62, 0.16), location=(0, 0, 2.62), bevel=0.02, mat=stone_mat)
cap = H.add_cone("RoofCap", 1.18, 0.62, location=(0, 0, 3.01), mat=stone_mat)
cap.rotation_euler[2] = math.radians(45)
trim = H.add_torus("GoldTrim", 0.3, 0.03, location=(0, 0, 2.18), mat=gold_mat)

# glowing crystal between the pillars
crystal = H.add_sphere("Crystal", 0.21, scale=(1, 1, 1.7), location=(0, 0, 2.18), mat=crystal_mat)
H.add_light("POINT", "CrystalLight", (0, 0, 2.2), (0, 0, 2.0), 18, 1.2)

# --- pine trees ---
def pine(x, y, s=1.0):
    trunk = H.add_cylinder("Trunk", 0.07 * s, 0.5 * s, vertices=10,
                           location=(x, y, 0.3 + 0.25 * s), mat=wood_mat)
    c1 = H.add_cone("PineLow", 0.42 * s, 0.85 * s, location=(x, y, 0.3 + 0.85 * s), mat=leaf_mat)
    c2 = H.add_cone("PineHigh", 0.3 * s, 0.7 * s, location=(x, y, 0.3 + 1.3 * s), mat=leaf_mat)
    return [trunk, c1, c2]

trees = pine(1.55, 0.95, 1.1) + pine(-1.62, 0.55, 0.9) + pine(-1.15, -1.4, 1.25) + pine(1.7, -0.9, 0.75)

# scattered rocks
rocks = []
for (x, y, s) in [(1.25, -1.35, 0.16), (-0.6, 1.7, 0.12), (0.4, -1.85, 0.1)]:
    r = H.add_sphere("Rock", s, scale=(1, 0.8, 0.65), location=(x, y, 0.34), mat=rock_mat)
    rocks.append(r)

# clouds: sphere clusters drifting around the island
clouds = []
for (cx, cy, cz, s) in [(4.2, 1.6, 0.4, 0.8), (-4.4, -1.2, -0.3, 1.0), (2.6, -4.3, 0.9, 0.65), (-2.8, 4.0, -0.7, 0.75)]:
    for (dx, dy, ds) in [(0, 0, 1.0), (0.55, 0.1, 0.7), (-0.5, -0.08, 0.75)]:
        c = H.add_sphere("Cloud", 0.55 * s * ds, scale=(1.35, 1, 0.62),
                         location=(cx + dx * s, cy + dy * s, cz), mat=cloud_mat)
        clouds.append(c)

subjects = [island, grass, step1, step2, monolith, roof, cap] + pillars
H.sun_and_sky(elevation=42, azimuth=140)
cam = H.add_camera("Camera", (7, -7, 4.5), (0, 0, 0.9), lens=50)
H.frame_objects(cam, subjects, azimuth=32, elevation=16, margin=1.18)
_target = __import__("mathutils").Vector((0, 0, 0.7))
cam.location = _target + (cam.location - _target) * 0.58
H.look_at(cam, (0, 0, 0.7))
bpy.context.scene.view_settings.exposure = 0.35

# gentle life: crystal bob (frame 1 is the still)
H.key(crystal, 1, location=(0, 0, 2.18))
H.key(crystal, 60, location=(0, 0, 2.34))
H.key(crystal, 120, location=(0, 0, 2.18))
H.set_interpolation(crystal, "BEZIER", extrapolation="CYCLES")
bpy.context.scene.frame_set(30)

H.save_blend(BLEND)  # so the addon's textures_dir() sits next to the .blend
print("BLEND_SAVED", BLEND)

# --- Muse texture through the addon's own pipeline ---
scene = bpy.context.scene
scene.muse.prompt = "ancient weathered mossy carved stone temple blocks, moss in the cracks, chisel marks"
scene.muse.style = "PBR_TEXTURE"
scene.muse.tileable = True
scene.muse.size = "1024x1024"
key, source, base_url, model = utils.api_settings(bpy.context)
print("KEY_SOURCE:", source, "| KEY_PRESENT:", bool(key))

texture_source = "procedural-fallback"
if key:
    try:
        prompt = utils.build_prompt(scene.muse.prompt, scene.muse.style, scene.muse.tileable)
        result = api_client.generate_image(prompt, key, size=scene.muse.size,
                                           base_url=base_url, model=model)
        bpy.context.view_layer.objects.active = monolith
        monolith.select_set(True)
        detail = operators._apply_generated_image(bpy.context, result, prompt,
                                                  apply_material=True, apply_gn=True)
        texture_source = f"Muse Image ({model}) via {source}: {detail}"
    except Exception as exc:  # noqa: BLE001 - fall back, never ship a broken scene
        import traceback; traceback.print_exc()
        print("MUSE_GENERATE_FAILED:", exc)

if texture_source == "procedural-fallback":
    import random
    rng = random.Random(7)
    img = bpy.data.images.new("Muse_procedural_stone", 512, 512)
    px = []
    for y in range(512):
        for x in range(512):
            block = ((x // 128) + (y // 128) * 4)
            n = rng.random() * 0.14
            base = 0.42 + ((block * 37) % 10) * 0.012 + n
            moss = 0.25 if (x % 128 < 5 or y % 128 < 5) and rng.random() < 0.6 else 0.0
            px += [base - moss * 0.4, base + moss * 0.25, base - moss * 0.3, 1.0] if False else [base - moss, base, base - moss * 0.5, 1.0]
    img.pixels = px
    img.pack()
    item = scene.muse_history.add()
    item.name = img.name; item.prompt = scene.muse.prompt; item.image_name = img.name
    item.created = "procedural fallback"
    from muse_ai_texture import nodes
    utils.ensure_uv_map(monolith)
    mat = nodes.apply_image_to_object(monolith, img, use_bump=True, use_roughness=True)
    nodes.add_gn_modifier(monolith, image=img, material=mat)

if texture_source != "procedural-fallback":
    from muse_ai_texture import nodes as _nodes
    _img = bpy.data.images.get(scene.muse_history[-1].image_name)
    _nodes.add_gn_modifier(monolith, image=_img, strength=0.045,
                           texture_scale=1.2,
                           material=monolith.active_material)
print("TEXTURE_SOURCE:", texture_source)
print("HISTORY:", [(i.name, i.prompt[:40]) for i in scene.muse_history])
print("MONOLITH_MODS:", [(m.type, getattr(m, 'node_group', None).name if m.type == 'NODES' else '') for m in monolith.modifiers])
print("MONOLITH_MAT:", monolith.active_material.name if monolith.active_material else None)
print("UV_ACTIVE:", bool(monolith.data.uv_layers.active))
H.report()

bpy.context.scene.frame_set(30)
if FINAL:
    H.set_render(engine="CYCLES", resolution=(1280, 960), samples=64, percentage=100)
    H.render_still(os.path.join(OUT, "sky_shrine.png"))
else:
    H.set_render(engine="CYCLES", resolution=(1152, 864), samples=24, percentage=50)
    H.render_still("/tmp/sky_shrine_preview.png")
H.save_blend(BLEND)
print("BUILD_DONE", "FINAL" if FINAL else "PREVIEW")
